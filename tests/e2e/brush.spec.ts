import { test, expect } from '@playwright/test';
test('brush strokes and stamps persist, export, undo, and integrated materials', async ({ page }) => {
 await page.setViewportSize({width:1500,height:1100}); await page.goto('/');
 await page.getByRole('button',{name:'筆刷',exact:true}).click();
 await expect(page.getByRole('button',{name:'版本',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'自由筆刷',exact:true}).click();
 const area=page.getByLabel('繪畫區'); const box=(await area.boundingBox())!;
 await page.mouse.move(box.x+80,box.y+90); await page.mouse.down(); await page.mouse.move(box.x+180,box.y+170,{steps:15}); await page.mouse.up();
 const draft=()=>page.evaluate(async()=> (await fetch('/api/designs/'+localStorage.getItem('wanshi:last-design'))).json());
 await expect.poll(async()=> (await draft()).design.layers.length).toBe(1);
 const stroke=(await draft()).design.layers[0]; expect(stroke.kind).toBe('stroke'); expect(stroke.points.length).toBeGreaterThan(10);
 await page.getByRole('button',{name:'獨立櫻花瓣',exact:true}).click();
 await area.click({position:{x:130,y:200}}); await area.click({position:{x:170,y:220}});
 await expect.poll(async()=> (await draft()).design.layers.length).toBe(3);
 await page.keyboard.press('Control+z');
 await expect.poll(async()=> (await draft()).design.layers.length).toBe(2);
 await page.keyboard.press('Control+Shift+z');
 await expect.poll(async()=> (await draft()).design.layers.length).toBe(3);
 await page.screenshot({path:'test-results/brush-editor.png',fullPage:true});
 await page.reload(); await expect(page.getByRole('button',{name:'筆刷',exact:true})).toBeVisible();
 expect((await draft()).design.layers[0]).toEqual(stroke);
 await page.locator('.canvas-material summary').click();
 await page.locator('.canvas-material').getByRole('button',{name:'黑',exact:true}).click();
 await expect.poll(async()=> (await draft()).design.material).toBe('black');
 await page.locator('.canvas-material summary').click();
 await page.getByRole('button',{name:'確認設計與加入購物車 ↗',exact:true}).click();
 await page.getByRole('button',{name:'確認並加入購物車',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'購物車'})).toBeVisible();
 await page.screenshot({path:'test-results/brush-cart.png',fullPage:true});
});
